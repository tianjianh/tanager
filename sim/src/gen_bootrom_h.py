#!/usr/bin/env python3
"""Writes tanager_bootrom.h for tanager-lockstep from rtl/uncore/bootrom/tg_bootrom_img_pkg.sv: the boot
ROM bytes as the RTL holds them, so Spike runs the same code. The package lists its 128-bit beats from the
highest index down ({beat N-1, ..., beat 0}); each beat is little-endian bytes from its address.

  gen_bootrom_h.py tg_bootrom_img_pkg.sv > tanager_bootrom.h
"""
import re
import sys


def main():
    text = open(sys.argv[1]).read()
    beats = re.findall(r"128'h([0-9a-fA-F_]+)", text)
    if not beats:
        sys.exit("gen_bootrom_h: no 128'h beats in " + sys.argv[1])
    data = b""
    for b in reversed(beats):  # beat 0 first
        v = int(b.replace("_", ""), 16)
        data += v.to_bytes(16, "little")
    print("// Generated by sim/src/gen_bootrom_h.py from rtl/uncore/bootrom/tg_bootrom_img_pkg.sv -- do not edit.")
    print("#pragma once")
    print("#include <cstdint>")
    print("static const uint8_t TANAGER_BOOTROM[] = {")
    for i in range(0, len(data), 16):
        print("  " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ",")
    print("};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
