#!/usr/bin/env python3
"""Generates the Goldschmidt seed ROM of the divide/sqrt unit (docs/spec/fpu.md, "Seed ROM").

2048 entries of 9 bits, address {sel, idx}:
  sel = 0  reciprocal:              idx = significand fraction bits 51:42 of mb in [1, 2);
                                    s = 0.1xxxxxxxxx (binary) ~ 1/mb
  sel = 1  reciprocal square root:  idx = {exponent parity, fraction bits 51:43};
                                    x = sig (parity 0, x in [1, 2)) or 2*sig (parity 1, x in [2, 4));
                                    y0 = 0.1xxxxxxxxx ~ 1/sqrt(x)
The 9-bit entry e encodes the value (512 + e) / 1024.

Each entry minimises the worst error the iteration sees over its index interval [lo, hi):
  reciprocal: max |1 - m*s|      square root: max |1 - x*y0^2|
Both are linear in m (or x), so the worst case is at an interval end. Errors are exact rationals.

Usage: gen_seed.py <out.svh> <out.h>
"""
import math
import sys
from fractions import Fraction as F


def best_entry(lo, hi, err):
    """Entry in [0, 511] minimising err(lo, hi, value); returns (entry, worst error)."""
    best = None
    for e in range(512):
        v = F(512 + e, 1024)
        w = err(lo, hi, v)
        if best is None or w < best[1]:
            best = (e, w)
    return best


def rcp_err(lo, hi, s):
    return max(abs(1 - lo * s), abs(1 - hi * s))


def rsq_err(lo, hi, y):
    return max(abs(1 - lo * y * y), abs(1 - hi * y * y))


def near(ideal, lo_e=0, hi_e=511):
    """Candidate entries around an ideal value (speeds up the exhaustive search)."""
    c = int(math.floor(ideal * 1024)) - 512
    return [e for e in range(c - 2, c + 3) if lo_e <= e <= hi_e]


def search(lo, hi, err, ideal):
    best = None
    for e in near(ideal):
        v = F(512 + e, 1024)
        w = err(lo, hi, v)
        if best is None or w < best[1]:
            best = (e, w)
    return best


def main():
    out_svh, out_h = sys.argv[1], sys.argv[2]
    rom = []
    worst_rcp = F(0)
    for i in range(1024):
        lo = 1 + F(i, 1024)
        hi = lo + F(1, 1024)
        e, w = search(lo, hi, rcp_err, 2.0 / float(lo + hi))
        rom.append(e)
        worst_rcp = max(worst_rcp, w)
    worst_rsq = F(0)
    for i in range(1024):
        parity, frac = i >> 9, i & 511
        lo = (1 + F(frac, 512)) * (2 if parity else 1)
        hi = lo + F(2 if parity else 1, 512)
        e, w = search(lo, hi, rsq_err, math.sqrt(2.0 / float(lo + hi)))
        rom.append(e)
        worst_rsq = max(worst_rsq, w)
    # Check the local search against the exhaustive one on a sample of intervals.
    for i in (0, 1, 511, 512, 1023):
        lo = 1 + F(i, 1024)
        hi = lo + F(1, 1024)
        assert best_entry(lo, hi, rcp_err)[1] == rcp_err(lo, hi, F(512 + rom[i], 1024))
    lg_rcp = math.log2(float(worst_rcp))
    lg_rsq = math.log2(float(worst_rsq))
    print(f"reciprocal:  max |1 - m*s|    = 2^{lg_rcp:.3f}")
    print(f"rsqrt:       max |1 - x*y0^2| = 2^{lg_rsq:.3f}")

    with open(out_svh, "w") as f:
        f.write("// Generated by tests/unit/fpu/gen_seed.py; do not edit.\n")
        f.write("// Goldschmidt seed ROM: address {sel, idx}; sel 0 = reciprocal, 1 = reciprocal square root.\n")
        f.write("// Entry e encodes (512 + e) / 1024. Worst errors: ")
        f.write(f"max |1 - m*s| = 2^{lg_rcp:.3f}, max |1 - x*y0^2| = 2^{lg_rsq:.3f}.\n")
        f.write("localparam logic [8:0] SEED_ROM [2048] = '{\n")
        for k in range(0, 2048, 16):
            row = ", ".join(f"9'h{v:03x}" for v in rom[k:k + 16])
            f.write(f"  {row}{',' if k + 16 < 2048 else ''}\n")
        f.write("};\n")
    with open(out_h, "w") as f:
        f.write("// Generated by tests/unit/fpu/gen_seed.py; do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n")
        f.write(f"// max |1 - m*s| = 2^{lg_rcp:.3f}, max |1 - x*y0^2| = 2^{lg_rsq:.3f}\n")
        f.write("static const uint16_t SEED_ROM[2048] = {\n")
        for k in range(0, 2048, 16):
            f.write("  " + ", ".join(f"0x{v:03x}" for v in rom[k:k + 16]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
