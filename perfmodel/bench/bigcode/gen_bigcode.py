"""Writes bigcode.c: a large instruction footprint walked in a fixed order, for instruction-prefetch and
I-cache decisions. NFUNC functions of straight-line integer work (two independent chains each) are called
directly, in a fixed shuffled order, from one driver that runs PASSES times. With the defaults the code is
about 150-200 KiB: far larger than a 32 KiB L1I, well inside a 1 MiB L2, like a kernel's hot paths.

  python3 gen_bigcode.py OUT.c [NFUNC]
"""
import random
import sys

out = sys.argv[1]
nfunc = int(sys.argv[2]) if len(sys.argv) > 2 else 1024
rng = random.Random(20261012)


def stmt():
    v, w = rng.sample(["a", "b", "c", "d"], 2)
    s = rng.randint(1, 63)
    k = rng.getrandbits(32) | 1
    return rng.choice([
        f"{v} ^= {w} >> {s};",
        f"{v} += {w} << {s % 32};",
        f"{v} = ({v} << {s}) | ({v} >> {64 - s});",
        f"{v} ^= 0x{k:x}u;",
        f"{v} += {w};",
        f"{v} -= {w} & 0x{k:x}u;",
        f"{v} = {v} * 0x{k:x}u + {w};" if rng.random() < 0.3 else f"{v} |= {w} >> 3;",
    ])


lines = ["/* Generated by bench/bigcode/gen_bigcode.py; do not edit. */", "#include <stdint.h>",
         "#include <stdio.h>", '#include "tgsim.h"', "", "#ifndef PASSES", "#define PASSES 20", "#endif", ""]
for i in range(nfunc):
    body = " ".join(stmt() for _ in range(rng.randint(12, 20)))
    lines.append(f"static __attribute__((noipa)) uint64_t f{i}(uint64_t a, uint64_t b) "
                 f"{{ uint64_t c = a ^ 0x{rng.getrandbits(20):x}u, d = b + {i}; {body} return (a ^ b) + (c ^ d); }}")
order = list(range(nfunc))
rng.shuffle(order)
lines.append("")
lines.append("static __attribute__((noipa)) uint64_t run(uint64_t a) {")
lines.append("  uint64_t b = 0x1234;")
for i in order:
    lines.append(f"  a = f{i}(a, b); b ^= a;")
lines.append("  return a ^ b;")
lines.append("}")
lines.append("")
lines.append("int main(void) {")
lines.append("  uint64_t a = 1;")
lines.append("  tg_region_start();")
lines.append("  for (int p = 0; p < PASSES; p++) a = run(a + (uint64_t)p);")
lines.append("  tg_region_stop();")
lines.append('  printf("bigcode funcs=%d a=%016llx\\n", ' + str(nfunc) + ', (unsigned long long)a);')
lines.append("  return 0;")
lines.append("}")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
