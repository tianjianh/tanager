#!/usr/bin/env python3
# Turns debugrom.bin (linked at DEBUG_BASE + 0x800) into the SystemVerilog package tg_dm imports:
# 128-bit beats (16 bytes, little-endian) from window offset 0x800, and the offsets of the symbols
# tg_dm needs. Usage: gen_svh.py debugrom.bin debugrom.sym
import sys
data = open(sys.argv[1], 'rb').read()
assert len(data) <= 256, "debug ROM image exceeds 256 bytes (0x800-0x8FF)"
data += b'\0' * (-len(data) % 16)
beats = [int.from_bytes(data[i:i+16], 'little') for i in range(0, len(data), 16)]
syms = {}
for line in open(sys.argv[2]):
    f = line.split()
    if len(f) == 3:
        syms[f[2]] = int(f[0], 16) & 0xFFFF
assert syms["_start"] == 0x800 and syms["exc_entry"] == 0x808, "debug ROM entries moved"
out = ["// Generated by sw/debugrom/gen_svh.py from sw/debugrom/debugrom.S -- do not edit.",
       "// Regenerate with `make -C sw/debugrom`; `make -C sw/debugrom check` verifies it is current.",
       "package tg_debugrom_img_pkg;",
       f"  localparam int DBGROM_BEATS = {len(beats)};",
       f"  localparam logic [15:0] DBGROM_HALT = 16'h{syms['halt']:04x};   // the abstract area's way back",
       "  localparam logic [DBGROM_BEATS-1:0][127:0] DBGROM_IMG = {"]
lines = [f"    128'h{b:032x}" for b in reversed(beats)]
out.append(",\n".join(lines))
out.append("  };")
out.append("endpackage")
print("\n".join(out))
