#!/usr/bin/env python3
# Turns bootrom.bin into the SystemVerilog package the boot ROM RTL imports:
# 128-bit beats (16 bytes, little-endian) for the used part of the 4 KiB ROM.
import sys
data = open(sys.argv[1], 'rb').read()
assert len(data) <= 4096, "boot ROM image exceeds 4 KiB"
data += b'\0' * (-len(data) % 16)
beats = [int.from_bytes(data[i:i+16], 'little') for i in range(0, len(data), 16)]
out = ["// Generated by sw/bootrom/gen_svh.py from sw/bootrom/bootrom.S -- do not edit.",
       "// Regenerate with `make -C sw/bootrom`; `make -C sw/bootrom check` verifies it is current.",
       "package tg_bootrom_img_pkg;",
       f"  localparam int BOOTROM_IMG_BEATS = {len(beats)};",
       "  localparam logic [BOOTROM_IMG_BEATS-1:0][127:0] BOOTROM_IMG = {"]
lines = [f"    128'h{b:032x}" for b in reversed(beats)]
out.append(",\n".join(lines))
out.append("  };")
out.append("endpackage")
print("\n".join(out))
